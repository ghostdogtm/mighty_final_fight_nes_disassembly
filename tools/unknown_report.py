"""Classify the bytes that neither the CDL nor the tracer reached (docs/unknown_data.md).

Reads the generated src/bank_XX.asm for runs marked '- - - - - -' (kind unknown) and looks at the ROM bytes."""
import re, sys, math, collections

ROM = open('Mighty Final Fight (U) [!].nes', 'rb').read()[16:16 + 0x20000]
MIN = 16


def runs_of(bank):
    out = []
    for l in open('src/bank_%02X.asm' % bank, encoding='utf8'):
        m = re.search(r';- - - - - - 0x\w+ \w\w:(\w{4}):', l)
        if not m:
            continue
        a = int(m.group(1), 16)
        n = l.split(';')[0].count('$')
        if out and out[-1][1] == a:
            out[-1][1] = a + n
        else:
            out.append([a, a + n])
    return out


def classify(data):
    n = len(data)
    if len(set(data)) == 1:
        return 'fill $%02X' % data[0]
    pop = sum(bin(x).count('1') for x in data) / n
    zeros = data.count(0) / n
    cnt = collections.Counter(data)
    ent = -sum(c / n * math.log2(c / n) for c in cnt.values())
    if pop < 2.1 and n >= 32:
        return 'low-density remnant (about 1-2 bits set per byte, unused)'
    if n >= 64 and ent > 6.3:
        return 'dense, high entropy (compressed or garbage)'
    if zeros > 0.4:
        return 'mostly zero'
    if n >= 48 and len(cnt) < n / 3:
        return 'structured table (few distinct values, probably animation / sprite metadata)'
    return 'mixed data'


lines = ['# Bytes not covered by CDL or tracing', '',
         'Generated by `tools/unknown_report.py`. Runs shorter than %d bytes are summed per bank only.' % MIN, '',
         '"low-density remnant" = bytes with only 1-2 bits set on average (random data would have 4), which looks like leftover',
         'memory dumped by the build tools into unused ROM space; "dense" runs look like random bytes. None of these is reached by the game in the CDL run.', '']
tot = collections.Counter()
rows = []
for b in range(16):
    base = 0x8000 + 0x2000 * (b % 2) if b < 14 else (0xC000 if b == 14 else 0xE000)
    small = 0
    for s, e in runs_of(b):
        o = b * 0x2000 + (s - (0x8000 if b < 14 and b % 2 == 0 else 0xA000 if b < 14 else base)) if True else 0
        # offset inside the bank
        o = b * 0x2000 + ((s - base) & 0x1FFF)
        data = ROM[o:o + (e - s)]
        if e - s < MIN:
            small += e - s
            continue
        c = classify(data)
        tot[c.split(' $')[0]] += e - s
        rows.append((b, s, e - s, c))
    if small:
        tot['short runs'] += small
lines += ['## Totals', '', '| class | bytes |', '|---|---|']
lines += ['| %s | %d |' % kv for kv in tot.most_common()]
lines += ['', '## Runs of %d bytes or more' % MIN, '', '| bank:addr | length | class |', '|---|---|---|']
for b, s, n, c in rows:
    lines.append('| %02X:%04X | %d | %s |' % (b, s, n, c))
open('docs/unknown_data.md', 'w', encoding='utf8').write('\n'.join(lines) + '\n')
print(dict(tot), len(rows))
