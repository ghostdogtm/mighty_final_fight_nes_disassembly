#!/usr/bin/env python3
"""Merge the output of tools/mesen/run_log.py and compare it with the FCEUX CDL.

usage: python tools/mesen/merge_logs.py RUN_DIR [--cdl FILE] [--write-cdl OUT.cdl] [--report docs/rom_reads.md]
                                         [--extents docs/table_extents.txt]

RUN_DIR holds run_*.exec / run_*.read (131072 bytes of 0/1 per PRG byte) and run_*.sites (one line per indexed
read instruction: "BB:PPPP BASE reg count idxmin idxmax").

Outputs:
  report   bytes executed / read that the CDL did not know, grouped into ranges per bank
  extents  per table base address: highest index seen by any reader -> minimal table length
  merged   a CDL = the original CDL OR code (bit 0) for executed bytes OR data (bit 1) for read bytes
"""
import argparse
import collections
import glob
import os

PRG = 131072
BANK = 0x2000


def load_flags(paths):
    acc = bytearray(PRG)
    for p in paths:
        d = open(p, 'rb').read()
        for i in range(min(len(d), PRG)):
            if d[i]:
                acc[i] = 1
    return acc


def ranges(offs):
    """sorted offsets -> [(start, end)] of contiguous runs"""
    out = []
    for o in offs:
        if out and o == out[-1][1] + 1:
            out[-1][1] = o
        else:
            out.append([o, o])
    return out


def fmt(o):
    b = o // BANK
    base = 0xC000 if b == 0x0E else 0xE000 if b == 0x0F else (0x8000 if b % 2 == 0 else 0xA000)
    return '%02X:%04X' % (b, base + o % BANK)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('run_dir')
    ap.add_argument('--cdl', default=os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
                                                  'Mighty Final Fight (U) [!].cdl'))
    ap.add_argument('--min-run', type=int, default=2, help='only list new ranges of at least this many bytes (1-byte hits are mostly prefetch artefacts)')
    ap.add_argument('--write-cdl')
    ap.add_argument('--report')
    ap.add_argument('--extents')
    a = ap.parse_args()

    execs = sorted(glob.glob(os.path.join(a.run_dir, 'run_*.exec')))
    reads = sorted(glob.glob(os.path.join(a.run_dir, 'run_*.read')))
    ex, rd = load_flags(execs), load_flags(reads)
    cdl = open(a.cdl, 'rb').read()[:PRG]

    new_ex = [i for i in range(PRG) if ex[i] and not cdl[i] & 1]
    new_rd = [i for i in range(PRG) if rd[i] and not cdl[i] & 3 and not ex[i]]
    code_cdl = sum(1 for c in cdl if c & 1)
    data_cdl = sum(1 for c in cdl if c & 2 and not c & 1)
    lines = ['# ROM reads seen by Mesen (headless bot runs)', '',
             'Generated by `tools/mesen/merge_logs.py` from %d runs (`tools/mesen/run_log.py`).' % len(execs), '',
             '| | bytes |', '|---|---|',
             '| executed in the runs | %d |' % sum(ex),
             '| executed and marked code by the FCEUX CDL | %d of %d |' % (sum(1 for i in range(PRG) if ex[i] and cdl[i] & 1), code_cdl),
             '| executed, **new** (not code in the CDL) | %d |' % len(new_ex),
             '| read as data in the runs | %d |' % sum(rd),
             '| read as data, **new** (CDL has neither code nor data) | %d |' % len(new_rd),
             '| CDL data bytes not read in these runs | %d of %d |' % (sum(1 for i in range(PRG) if cdl[i] & 2 and not cdl[i] & 1 and not rd[i]), data_cdl),
             '']
    for title, offs in (('Newly executed ranges', new_ex), ('Newly read ranges', new_rd)):
        lines += ['## %s (%d bytes or more)' % (title, a.min_run), '']
        rs = [r for r in ranges(offs) if r[1] - r[0] + 1 >= a.min_run]
        if not rs:
            lines += ['none', '']
            continue
        lines += ['| range | bytes |', '|---|---|']
        for lo, hi in rs:
            lines.append('| %s-%04X | %d |' % (fmt(lo), (0xC000 if lo // BANK == 14 else 0xE000 if lo // BANK == 15 else 0x8000 if (lo // BANK) % 2 == 0 else 0xA000) + hi % BANK, hi - lo + 1))
        lines.append('')
    if a.report:
        open(a.report, 'w', newline='\n').write('\n'.join(lines))
    else:
        print('\n'.join(lines))

    if a.write_cdl:
        out = bytearray(open(a.cdl, 'rb').read())
        for i in range(PRG):
            if ex[i]:
                out[i] |= 1
            if rd[i] and not ex[i]:
                out[i] |= 2
        open(a.write_cdl, 'wb').write(out)
        print('merged CDL written to', a.write_cdl)

    # table extents
    agg = {}
    for p in glob.glob(os.path.join(a.run_dir, 'run_*.sites')):
        for ln in open(p):
            f = ln.split()
            if len(f) != 6:
                continue
            key = (int(f[1], 16), f[2], f[0])
            n, lo, hi = int(f[3]), int(f[4]), int(f[5])
            v = agg.get(key)
            agg[key] = (n, lo, hi) if v is None else (v[0] + n, min(v[1], lo), max(v[2], hi))
    by_base = collections.defaultdict(list)
    for (base, reg, label), (n, lo, hi) in agg.items():
        by_base[base].append((label, reg, n, lo, hi))
    ext = ['# base  max index seen  readers (label reg count idx range)', '']
    for base in sorted(by_base):
        rs = by_base[base]
        top = max(r[4] for r in rs)
        ext.append('%04X  max=%d (%d entries at least)  %s' % (base, top, top + 1,
                   '; '.join('%s %s x%d [%d..%d]' % r for r in sorted(rs))))
    if a.extents:
        open(a.extents, 'w', newline='\n').write('\n'.join(ext) + '\n')
    else:
        print('\n'.join(ext))


if __name__ == '__main__':
    main()
